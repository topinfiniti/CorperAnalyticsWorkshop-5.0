-- difference between  previous and current sales
SELECT
    SalesPerson,
    SaleDate,
    SalesAmount,

    LAG(SalesAmount) OVER
    (
        PARTITION BY SalesPerson
        ORDER BY SaleDate
    ) AS PreviousSales,

    SalesAmount -
    LAG(SalesAmount) OVER
    (
        PARTITION BY SalesPerson
        ORDER BY SaleDate
    ) AS SalesDifference

